def build_structure_prompt(topic: str) -> str:
    return f"""
Ты — аналитик SMM студенческого строительного отряда.

На основе запроса пользователя определи СТРОГУЮ СТРУКТУРУ поста.

❗ НЕ ПИШИ сам пост
❗ НЕ ИСПОЛЬЗУЙ эмоции
❗ Верни ТОЛЬКО JSON, без пояснений

Формат JSON:
- squad_name: string
- event: string
- season_or_date: string | null
- post_type: one of ["знакомка", "отчет", "анонс", "поздравление"]
- key_actions: string[]
- tone: string
- forbidden_topics: string[]

Запрос пользователя:
"{topic}"
""".strip()


def build_generation_prompt(
    structure: dict,
    examples: list[str],
    length: str,
    force_rules: bool = False
) -> str:
    examples_block = "\n\n".join(
        f"Пример {i+1}:\n{txt}" for i, txt in enumerate(examples)
    )

    rules_block = """
❗ ОБЯЗАТЕЛЬНЫЕ ПРАВИЛА:

- Последняя строка должна быть в формате:
  "С любовью, ваш 🌅 ССО «Урал»🌅"
- Не используй служебные блоки
- Пиши от первого лица во множественном числе
- Пост должен соответствовать теме 
- Текст должен быть во множественном числе от первого лица (мы, наш) 
- Объем основного текста должен составлять примерно 3-5 абзацев, НЕ ВКЛЮЧАЯ заголовок и последнее сообщение 
- Текст должен звучать живо и по-человечески 
- Можно использовать эмодзи (если это уместно) 
- Не упоминай другие отряды 
- Не используй клише и канцелярит 
- Если примеры постов от женских отрядов, то меняй на мужской, так как мы мужской отряд 
- Это пост для ВК, не статья и не пресс-релиз 
- Пост рассчитан на аудиторию, которой интересно то что делает наш отряд 
- Пост обращается к подписчикам 
- В первую очередь пост показывает то, что делал наш отряд ССО «Урал», и если нужно, то с кем он это делал 
- Заголовок поста (первая строка текста) - 1-3 слова, название проводимого мероприятия, НЕ ОБРАЩЕНИЕ 
- В посте не должно быть обращения к какому-то отряду, только упоминание, если мероприятие было с ними 
- В посте НЕ ДОЛЖНО быть обращения к нашему же отряду (ССО «Урал») 
- В посте НЕ ДОЛЖНО БЫТЬ УПОМИНАНИЯ ССО «Урал» нигде, кроме последнего сообщения 
""".strip()

    strict_block = """
❗❗ ВНИМАНИЕ:
Ты уже нарушал правила ранее.
Сейчас запрещено:
- импровизировать
- менять формат
- добавлять лишние элементы
""".strip()

    prompt = f"""
Ты — пресс-секретарь паблика ВКонтакте.

Тема: {structure['event']}
Тип поста: {structure['post_type']}
Тон: {structure['tone']}
Объём: {length}

{rules_block}

{"\n" + strict_block if force_rules else ""}

Примеры:
{examples_block}

Напиши итоговый текст поста.
""".strip()

    return prompt


def build_fix_prompt(original_text, errors, structure):
    return f"""
Ты — редактор постов ВКонтакте.

Твоя задача — минимально исправить текст, чтобы:
- название отряда упоминалось ТОЛЬКО в финальной строке
- финальная строка была в формате:
  "С любовью, ваш 🌅 ССО «Урал»🌅"

❗ Разрешено:
- убрать лишние упоминания отряда
- переписать заголовок
- удалить служебные блоки

❗ Запрещено:
- менять тему
- менять тип поста
- добавлять новые события

ИСХОДНЫЙ ТЕКСТ:
{original_text}

Верни исправленный текст.
""".strip()


